export function translate(language, original, values = {}) {
  const result = language === 'en' && Object.hasOwn(english, original) ? english[original] : original
  return result.replace(/\{(\w+)\}/g, (token, key) => Object.hasOwn(values, key) ? String(values[key]) : token)
}

export function acceptLanguage(header = '') {
  const preference = header.split(',').map(item => {
    const [tag, weight] = item.trim().toLowerCase().split(';q=')
    return { tag: tag.split('-')[0], weight: weight === undefined ? 1 : Number(weight) }
  }).filter(item => ['sk', 'en'].includes(item.tag) && item.weight > 0).sort((a, b) => b.weight - a.weight)
  return preference[0]?.tag ?? 'sk'
}
